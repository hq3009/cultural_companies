          ONLY_FULL_GROUP_BY 模式下 core.* 与 GROUP BY 冲突。
   5. 03：删除尾随逗号；tax_amt 改从 company_ns 取（company_nb 没有该列）；
          把去年写成 0 的占位指标尽量补实。
   6. 05 / 06：社保段改用本文件统一建的 company_sb_jbxx，不再混用明细链路。
   7. 07：全部表加 rpt_ 前缀并补 DROP；社保表不存在的 issue_end_dt 改为
          pens_pay_ym；comp_type 的数字代码与中文名称两种形态都做兼容；
