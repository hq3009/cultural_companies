    reg_org             -- 登记机关：2026 补入，供地区分布统计使用
FROM (
    -- 按信用代码去重，保留成立日期最新的一条，避免下游多表 JOIN 出现行数膨胀
    SELECT c.*,
           ROW_NUMBER() OVER (PARTITION BY c.uni_social_crd_cd ORDER BY c.est_dt DESC) AS rn
    FROM company c
) t
WHERE rn = 1;

