/* ============================================================================
   宁波市文旅经营主体数据分析 · 2026 年度整合脚本
   文件：src_cloud/08_culture_2026.sql

   【这个文件是什么】
   把去年分散在 src_cloud/00 ~ 07 的脚本按主链路合并成一份可以从上到下
   顺序执行的单一脚本，以后续跑只需要维护这一个文件。四个 02 变体中只保留
   聚合分步版作为主实现，草稿、明细版与重复的统计脚本未纳入，清单见下方。
   每个 SECTION 的开头都注明了对应的去年文件名，方便回溯。

   【运行环境】
   MySQL 8.0+，云服务器政务数据共享库。源表为 columns.md 中登记的 dw_* 表，
   全部以统一社会信用代码 uni_social_crd_cd 关联。需要有建表权限；
   若云端只允许临时表，请把本文件中的 CREATE TABLE 改成 CREATE TEMPORARY TABLE。

   【执行方式】
   1. 建议先在数据库客户端里分段选中执行，每段跑完看一眼结果行数再继续；
      所有建表语句前都加了 DROP TABLE IF EXISTS，整文件重复跑不会报表已存在。
   2. 执行前先备份库中已有的 company_*、wenhua、lvyou、wenlv、rpt_* 表。
   3. SECTION 7 是执行后的核对清单，务必跑一遍再取报告数字。

   【两套口径，不要混淆】
   SECTION 2：业务筛选口径。用“文旅行业代码清单 + 经营范围关键词”从市场主体
              总表筛出 company，再切成 wenhua / lvyou / wenlv 三个子集。
              SECTION 3 ~ 5 的企业画像与统计全部基于这一口径。
   SECTION 6：报告统计口径。按《国民经济行业分类》《文化及相关产业分类 2018》
              《旅游及相关产业分类 2018》三套国家分类标准各自建表，再取并集
              得到 rpt_wenlv_all，专门用于填写报告里的经营主体总量。
   去年的 07_report.sql 与 01_comp_init.sql 用了同一批表名 wenlv / wenhua /
   lvyou 却含义不同，顺序执行会互相覆盖。本文件把报告口径的表统一加了 rpt_
   前缀，两套口径互不干扰，但数字不可混用。

   【去年四个 02 脚本只保留了一个】
   02_comp_ext_aggr.sql / _aggr_steps.sql / _full.sql / _full_steps.sql 是
   “聚合 vs 明细”×“单脚本 vs 分步”的四种实现，输出表名与字段名互不兼容。
   本文件采用 02_comp_ext_aggr_steps.sql（聚合、分步、一企业一行）作为主实现，
   因为它用窗口函数先在源表内预聚合，能避免多张一对多表连乘导致的计数失真。
   另外把明细链路里独有的社保、担保、科技认定、公共信用分四块补进 SECTION 3，
   使 05 / 06 的社保统计和 03 的占位指标能够真正算出来。
   其余三个脚本仍保留在原文件中，需要原始明细时再单独查看。

   【相对去年脚本的修正（重要）】
   1. 00：四个单列代码表 CREATE TABLE 最后一列的尾随逗号删除；TYPE 加反引号；
          lvyou_codes 里重复的 8930 去重。
   2. 01：校验段补逗号、三处 COUNT 补 SELECT；wenlv 的 IN 清单补两处逗号
          （去年缺逗号会被 MySQL 静默拼成 77147715 等，几乎筛不到文旅融合企业）。
   3. 01：company_core 按信用代码去重，并补入 domdi_strict、reg_org 两个字段
          （去年的 03_stats_full 等脚本引用了 domdi_strict，但 company_core 没有）。
