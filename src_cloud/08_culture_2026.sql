-- 0.1 确认源表可读，并核对企业类型字段的实际取值形态。
--     去年脚本对 comp_type 有两套假设：01 的注释说是中文名称，07 用数字代码。
--     下面这句的结果决定 SECTION 6 里哪种兼容分支生效，务必先看一眼。
SELECT comp_type, COUNT(*) AS cnt
FROM dw_zj_scjdgl_scztxx
GROUP BY comp_type
ORDER BY cnt DESC
LIMIT 20;

-- 0.2 确认行业代码字段形态。四位国民经济行业小类代码，如 8610、6421。
SELECT indv_nm, COUNT(*) AS cnt
FROM dw_zj_scjdgl_scztxx
GROUP BY indv_nm
ORDER BY cnt DESC
LIMIT 10;


